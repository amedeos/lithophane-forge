"""End to end with the PrusaSlicer command line (deselect with -m 'not slicer')."""

import zipfile
from pathlib import Path

import pytest

from lithophane_forge import forge, printers, profiles, slicer, threemf
from lithophane_forge.forge import Job
from lithophane_forge.optics import DEFAULTS

pytestmark = [
    pytest.mark.slicer,
    pytest.mark.skipif(slicer.command() is None, reason="PrusaSlicer not installed"),
]


@pytest.fixture(scope="module")
def made(tmp_path_factory):
    from conftest import write_photo

    tmp = tmp_path_factory.mktemp("slice")
    photo = write_photo(tmp / "photo.png")
    setup = printers.setup("mk4", "petg")
    j = Job(
        photo=photo,
        setup=setup,
        optics=DEFAULTS["petg"],
        out=tmp / "out",
        width=40,
        pitch=0.4,
        slice=True,
    )
    return j, forge.make(j)


def test_project_and_gcode(made):
    j, res = made
    assert res.files["bgcode"].stat().st_size > 1000
    assert res.sliced["printer"] == j.setup.printer_preset
    assert res.sliced["filament"] == j.setup.filament_preset
    with zipfile.ZipFile(res.files["3mf"]) as z:
        cfg = z.read(threemf.CONFIG).decode()
    assert cfg.startswith("; generated by PrusaSlicer")
    assert "; binary_gcode = 1" in cfg
    assert f"; print_settings_id = {j.setup.print_preset}" in cfg


def test_project_carries_the_printer(made, tmp_path):
    """Sliced without any preset option, the project gives the same printer and settings."""
    j, res = made
    cmd = slicer.command()
    out = tmp_path / "check.gcode"
    with slicer.datadir(j.setup, profiles.find_bundle(), slicer.command()) as dd:
        slicer.run(cmd, res.files["3mf"], out, extra=tuple(dd))
    text = out.read_text(encoding="utf-8", errors="replace")
    info = slicer.summary(out)
    assert info["printer"] == j.setup.printer_preset
    assert info["filament_g"] == res.sliced["filament_g"]
    assert "; fill_density = 100%" not in text  # the 100 % is the object's, not the preset's
    assert ";TYPE:Skirt/Brim" in text


def test_needs_no_support(made, tmp_path):
    """With automatic supports for anything leaning out more than our limit (plus 5 degrees),
    PrusaSlicer finds nothing to support."""
    j, res = made
    out = tmp_path / "support.gcode"
    threshold = 90 - j.max_overhang - 5  # PrusaSlicer measures from the horizontal
    extra = (
        "--support-material",
        "--support-material-auto",
        "--dont-support-bridges",
        "--support-material-threshold",
        f"{threshold:g}",
    )
    with slicer.datadir(j.setup, profiles.find_bundle(), slicer.command()) as dd:
        slicer.run(slicer.command(), res.files["3mf"], out, extra=(*dd, *extra))
    assert slicer.summary(out)["support_lines"] == 0


def test_other_nozzle(tmp_path):
    """Presets for a 0.6 nozzle reach the project (PrusaSlicer does not swap them)."""
    from conftest import write_photo

    setup = printers.setup(
        "mk4",
        "petg",
        printer_preset="Original Prusa MK4 Input Shaper 0.6 nozzle",
        print_preset="0.15mm STRUCTURAL @MK4IS 0.6",
        filament_preset="Prusament PETG @PGIS 0.6",
    )
    j = Job(
        photo=write_photo(tmp_path / "p.png"),
        setup=setup,
        optics=DEFAULTS["petg"],
        out=tmp_path / "out",
        width=20,
        pitch=1.0,
    )
    res = forge.make(j)
    with zipfile.ZipFile(res.files["3mf"]) as z:
        cfg = z.read(threemf.CONFIG).decode()
    assert "; nozzle_diameter = 0.6" in cfg
    assert '; filament_settings_id = "Prusament PETG @PGIS 0.6"' in cfg


@pytest.mark.parametrize("key", sorted(printers.PRINTERS))
def test_every_printer_slices(key, tmp_path):
    """The three presets of every printer go together (PrusaSlicer accepts them)."""
    from conftest import write_photo

    j = Job(
        photo=write_photo(tmp_path / "p.png"),
        setup=printers.setup(key, "petg"),
        optics=DEFAULTS["petg"],
        out=tmp_path / "out",
        width=20,
        pitch=1.0,
    )
    res = forge.make(j)
    assert res.sliced["printer"] == j.setup.printer_preset
    assert Path(res.files["3mf"]).is_file()
