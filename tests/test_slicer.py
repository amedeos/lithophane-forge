@pytest.mark.parametrize(
    "kw",
    [
        {"shape": "shaped", "width": 40, "hole": True},
        {"shape": "flat", "width": 40, "stand": True, "hole": True},
        {"shape": "cylinder", "diameter": 60, "height": 30, "lamp_base": True},
    ],
    ids=["shaped", "flat+stand", "cylinder+base"],
)
def test_shapes_and_accessories_slice(kw, tmp_path):
    """Every part slices; the joined volumes print as one body (no part is lost)."""
    from conftest import write_photo

    j = Job(
        photo=write_photo(tmp_path / "p.png"),
        setup=printers.setup("mk4", "petg"),
        optics=DEFAULTS["petg"],
        out=tmp_path / "out",
        pitch=0.5,
        **kw,
    )
    res = forge.make(j)
    for name, info in res.sliced.items():
        assert float(info["filament_g"]) > 0.5, name
    assert set(res.sliced) == {"lithophane", *res.accessories}


def test_colour_changes_reach_the_gcode(tmp_path):
    """The M600s in the sliced G-code are exactly the planned ones."""
    import json

    import numpy as np
    from PIL import Image
    from test_palette import sunset

    photo = tmp_path / "sunset.png"
    Image.fromarray((sunset(90, 120) * 255).astype(np.uint8)).save(photo)
    setup = printers.setup("mk4", "petg")
    j = Job(
        photo=photo,
        setup=setup,
        optics=DEFAULTS["petg"],
        out=tmp_path / "out",
        mode="color",
        colors=3,
        width=50,
        pitch=0.5,
    )
    res = forge.make(j)
    plan = json.loads(res.files["plan"].read_text(encoding="utf-8"))
    planned = [z for z, _ in plan["colour_changes"]]
    out = tmp_path / "check.gcode"
    with slicer.datadir(setup, profiles.find_bundle(), slicer.command()) as dd:
        slicer.run(slicer.command(), res.files["3mf"], out, extra=tuple(dd))
    assert slicer.summary(out)["m600_z"] == pytest.approx(planned)
    # the project starts with the first planned filament's colour, also without options
    first = plan["colour"]["print"]["filaments"][0]["hex"]
    assert f"; filament_colour = {first}" in out.read_text(encoding="utf-8")


